/**
 * The {@code AndroidKeyStore} JCA provider, which a device's keystore daemon backs and Robolectric
 * does not have: {@code KeyStore.getInstance("AndroidKeyStore")} and {@code
 * KeyGenerator.getInstance("AES", "AndroidKeyStore")} threw {@code NoSuchProviderException}, which
 * stops every app that encrypts its preferences (androidx.security's {@code MasterKey} and {@code
 * EncryptedSharedPreferences}, Tink's {@code AndroidKeysetManager}) at startup.
 *
 * <p>Keys are software keys, generated by the JDK from the {@code KeyGenParameterSpec} the app
 * passes (AES and HMAC secret keys; EC and RSA key pairs, each with a self-signed {@code CN=fake}
 * certificate, as the platform issues when the app asks for no attestation) and kept in memory
 * under their alias for the life of the simulator. Nothing is enforced: not the purposes, block
 * modes or paddings the spec names, not user authentication, not hardware backing.
 */
public final class AndroidKeyStoreProvider extends Provider {

  static final String NAME = "AndroidKeyStore";

  /** The keys, by alias: what the keystore daemon holds for the app's uid. */
  private static final Map<String, Stored> keys = new ConcurrentHashMap<>();

  private static final class Stored {
    final Key key;
    final Certificate[] chain;
    final Date created = new Date();

    Stored(Key key, Certificate[] chain) {
      this.key = key;
      this.chain = chain;
    }
  }

  /** Adds the provider once, before the application's {@code onCreate()}. */
  static synchronized void install() {
    if (Security.getProvider(NAME) == null) Security.addProvider(new AndroidKeyStoreProvider());
  }

  public AndroidKeyStoreProvider() {
    super(NAME, "1.0", "The simulator's software stand-in for Android's keystore");
    put("KeyStore.AndroidKeyStore", Store.class.getName());
    put("KeyGenerator.AES", Aes.class.getName());
    put("KeyGenerator.HmacSHA1", HmacSha1.class.getName());
    put("KeyGenerator.HmacSHA224", HmacSha224.class.getName());
    put("KeyGenerator.HmacSHA256", HmacSha256.class.getName());
    put("KeyGenerator.HmacSHA384", HmacSha384.class.getName());
    put("KeyGenerator.HmacSHA512", HmacSha512.class.getName());
    put("KeyPairGenerator.EC", EcKeyPairs.class.getName());
    put("KeyPairGenerator.RSA", RsaKeyPairs.class.getName());
  }

  /** {@code KeyGenParameterSpec}'s alias, read reflectively: the type is framework, API 23. */
  private static String alias(AlgorithmParameterSpec spec) {
    try {
      return (String) spec.getClass().getMethod("getKeystoreAlias").invoke(spec);
    } catch (ReflectiveOperationException e) {
      throw new IllegalArgumentException(
          "AndroidKeyStore keys are generated from a KeyGenParameterSpec, not " + spec, e);
    }
  }

  private static int keySize(AlgorithmParameterSpec spec) {
    try {
      return (int) spec.getClass().getMethod("getKeySize").invoke(spec);
    } catch (ReflectiveOperationException e) {
      return -1;
    }
  }

  private static AlgorithmParameterSpec algorithmSpec(AlgorithmParameterSpec spec) {
    try {
      return (AlgorithmParameterSpec)
          spec.getClass().getMethod("getAlgorithmParameterSpec").invoke(spec);
    } catch (ReflectiveOperationException e) {
      return null;
    }
  }

  // ---------------------------------------------------------------------------------------------
  // Key generation

  /**
   * AES and HMAC keys, one subclass per algorithm: the JCA builds each through its no-argument
   * constructor and does not say which algorithm it was asked for.
   */
  abstract static class SecretKeys extends KeyGeneratorSpi {
    private String alias;
    private int size = -1;
    private SecureRandom random;

    @Override
    protected void engineInit(SecureRandom random) {
      throw new IllegalStateException("AndroidKeyStore needs a KeyGenParameterSpec");
    }

    @Override
    protected void engineInit(AlgorithmParameterSpec params, SecureRandom random)
        throws InvalidAlgorithmParameterException {
      alias = alias(params);
      size = keySize(params);
      this.random = random;
    }

    @Override
    protected void engineInit(int keysize, SecureRandom random) {
      throw new IllegalStateException("AndroidKeyStore needs a KeyGenParameterSpec");
    }

    @Override
    protected SecretKey engineGenerateKey() {
      if (alias == null) throw new IllegalStateException("not initialized");
      try {
        KeyGenerator generator = KeyGenerator.getInstance(algorithm);
        if (size > 0) generator.init(size, random != null ? random : new SecureRandom());
        SecretKey key = generator.generateKey();
        keys.put(alias, new Stored(key, null));
        return key;
      } catch (java.security.GeneralSecurityException e) {
        throw new IllegalStateException(e);
      }
    }

    private final String algorithm;

    SecretKeys(String algorithm) {
      this.algorithm = algorithm;
    }
  }

  public static final class Aes extends SecretKeys {
    public Aes() {
      super("AES");
    }
  }

  public static final class HmacSha1 extends SecretKeys {
    public HmacSha1() {
      super("HmacSHA1");
    }
  }

  public static final class HmacSha224 extends SecretKeys {
    public HmacSha224() {
      super("HmacSHA224");
    }
  }

  public static final class HmacSha256 extends SecretKeys {
    public HmacSha256() {
      super("HmacSHA256");
    }
  }

  public static final class HmacSha384 extends SecretKeys {
    public HmacSha384() {
      super("HmacSHA384");
    }
  }

  public static final class HmacSha512 extends SecretKeys {
    public HmacSha512() {
      super("HmacSHA512");
    }
  }

  /** For tests: forgets every key. */
  static void forgetAll() {
    keys.clear();
  }

  /** EC key pairs: P-256 unless the spec names a curve. */
  public static final class EcKeyPairs extends Pairs {
    public EcKeyPairs() {
      super("EC", "SHA256withECDSA");
    }
  }

  /** RSA key pairs: 2048 bits unless the spec says otherwise. */
  public static final class RsaKeyPairs extends Pairs {
    public RsaKeyPairs() {
      super("RSA", "SHA256withRSA");
    }
  }

  abstract static class Pairs extends KeyPairGeneratorSpi {
    private final String algorithm;
    private final String signature;
    private String alias;
    private AlgorithmParameterSpec spec;
    private int size = -1;
    private SecureRandom random;

    Pairs(String algorithm, String signature) {
      this.algorithm = algorithm;
      this.signature = signature;
    }

    @Override
    public void initialize(int keysize, SecureRandom random) {
      throw new IllegalStateException("AndroidKeyStore needs a KeyGenParameterSpec");
    }

    @Override
    public void initialize(AlgorithmParameterSpec params, SecureRandom random) {
      alias = alias(params);
      spec = algorithmSpec(params);
      size = keySize(params);
      this.random = random != null ? random : new SecureRandom();
    }

    @Override
    public KeyPair generateKeyPair() {
      if (alias == null) throw new IllegalStateException("not initialized");
      try {
        KeyPairGenerator generator = KeyPairGenerator.getInstance(algorithm);
        if (spec instanceof ECGenParameterSpec || spec instanceof RSAKeyGenParameterSpec) {
          generator.initialize(spec, random);
        } else if (algorithm.equals("EC")) {
          generator.initialize(new ECGenParameterSpec(curve(size)), random);
        } else {
          generator.initialize(size > 0 ? size : 2048, random);
        }
        KeyPair pair = generator.generateKeyPair();
        X509Certificate certificate = SelfSigned.certificate(pair, signature);
        keys.put(alias, new Stored(pair.getPrivate(), new Certificate[] {certificate}));
        return pair;
      } catch (java.security.GeneralSecurityException e) {
        throw new IllegalStateException(e);
      }
    }

    private static String curve(int size) {
      switch (size) {
        case 384:
          return "secp384r1";
        case 521:
          return "secp521r1";
        default:
          return "secp256r1";
      }
    }
  }

  // ---------------------------------------------------------------------------------------------
  // The store

  /** {@code KeyStore.getInstance("AndroidKeyStore")}: the keys above, by alias. */
  public static final class Store extends KeyStoreSpi {
    @Override
    public Key engineGetKey(String alias, char[] password) {
      Stored stored = keys.get(alias);
      return stored == null ? null : stored.key;
    }

    /** As Android's keystore: an entry is read without a password ({@code getEntry(alias, null)}). */
    @Override
    public java.security.KeyStore.Entry engineGetEntry(
        String alias, java.security.KeyStore.ProtectionParameter protection) {
      Stored stored = keys.get(alias);
      if (stored == null) return null;
      if (stored.key instanceof PrivateKey) {
        return new java.security.KeyStore.PrivateKeyEntry((PrivateKey) stored.key, stored.chain);
      }
      if (stored.key instanceof SecretKey) {
        return new java.security.KeyStore.SecretKeyEntry((SecretKey) stored.key);
      }
      return new java.security.KeyStore.TrustedCertificateEntry(stored.chain[0]);
    }

    @Override
    public Certificate[] engineGetCertificateChain(String alias) {
      Stored stored = keys.get(alias);
      return stored == null || stored.chain == null ? null : stored.chain.clone();
    }

    @Override
    public Certificate engineGetCertificate(String alias) {
      Stored stored = keys.get(alias);
      return stored == null || stored.chain == null || stored.chain.length == 0
          ? null
          : stored.chain[0];
    }

    @Override
    public Date engineGetCreationDate(String alias) {
      Stored stored = keys.get(alias);
      return stored == null ? null : new Date(stored.created.getTime());
    }

    @Override
    public void engineSetKeyEntry(String alias, Key key, char[] password, Certificate[] chain)
        throws KeyStoreException {
      if (key instanceof PrivateKey && (chain == null || chain.length == 0)) {
        throw new KeyStoreException("a private key needs its certificate chain");
      }
      keys.put(alias, new Stored(key, chain == null ? null : chain.clone()));
    }

    @Override
    public void engineSetKeyEntry(String alias, byte[] key, Certificate[] chain)
        throws KeyStoreException {
      throw new KeyStoreException("AndroidKeyStore does not import encoded keys");
    }

    @Override
    public void engineSetCertificateEntry(String alias, Certificate cert) {
      keys.put(alias, new Stored(null, new Certificate[] {cert}));
    }

    @Override
    public void engineDeleteEntry(String alias) {
      keys.remove(alias);
    }

    @Override
    public Enumeration<String> engineAliases() {
      return Collections.enumeration(new java.util.TreeSet<>(keys.keySet()));
    }

    @Override
    public boolean engineContainsAlias(String alias) {
      return keys.containsKey(alias);
    }

    @Override
    public int engineSize() {
      return keys.size();
    }

    @Override
    public boolean engineIsKeyEntry(String alias) {
      Stored stored = keys.get(alias);
      return stored != null && stored.key != null;
    }

    @Override
    public boolean engineIsCertificateEntry(String alias) {
      Stored stored = keys.get(alias);
      return stored != null && stored.key == null;
    }

    @Override
    public String engineGetCertificateAlias(Certificate cert) {
      for (Map.Entry<String, Stored> e : keys.entrySet()) {
        Certificate[] chain = e.getValue().chain;
        if (chain != null && chain.length > 0 && chain[0].equals(cert)) return e.getKey();
      }
      return null;
    }

    @Override
    public void engineStore(OutputStream stream, char[] password) {
      throw new UnsupportedOperationException("AndroidKeyStore cannot be written out");
    }

    @Override
    public void engineLoad(InputStream stream, char[] password) {
      // load(null) is how an app opens the keystore; there is nothing to read.
    }
  }

  // ---------------------------------------------------------------------------------------------

  /**
   * A self-signed X.509 v3 certificate for a generated key pair, DER-encoded by hand (the JDK has
   * no public certificate builder, and only BouncyCastle's provider half is on the class path):
   * subject and issuer {@code CN=fake}, valid from now for 30 years.
   */
  static final class SelfSigned {
    static X509Certificate certificate(KeyPair pair, String signatureAlgorithm)
        throws java.security.GeneralSecurityException {
      byte[] algorithm = algorithmIdentifier(signatureAlgorithm);
      byte[] name = seq(set(seq(cat(oid(2, 5, 4, 3), tlv(0x0c, "fake".getBytes(StandardCharsets.UTF_8))))));
      long now = System.currentTimeMillis();
      byte[] validity =
          seq(cat(time(new Date(now - 60_000)), time(new Date(now + 30L * 365 * 86_400_000))));
      byte[] serial = tlv(0x02, new BigInteger(63, new SecureRandom()).add(BigInteger.ONE).toByteArray());
      byte[] version = tlv(0xa0, tlv(0x02, new byte[] {2}));
      byte[] tbs =
          seq(cat(version, serial, algorithm, name, validity, name, pair.getPublic().getEncoded()));
      Signature signer = Signature.getInstance(signatureAlgorithm);
      signer.initSign(pair.getPrivate());
      signer.update(tbs);
      byte[] signature = signer.sign();
      byte[] bits = new byte[signature.length + 1];
      System.arraycopy(signature, 0, bits, 1, signature.length);
      byte[] der = seq(cat(tbs, algorithm, tlv(0x03, bits)));
      return (X509Certificate)
          CertificateFactory.getInstance("X.509").generateCertificate(new ByteArrayInputStream(der));
    }

    private static byte[] algorithmIdentifier(String signatureAlgorithm) {
      switch (signatureAlgorithm) {
        case "SHA256withECDSA":
          return seq(oid(1, 2, 840, 10045, 4, 3, 2));
        case "SHA256withRSA":
          return seq(cat(oid(1, 2, 840, 113549, 1, 1, 11), new byte[] {0x05, 0x00}));
        default:
          throw new IllegalArgumentException(signatureAlgorithm);
      }
    }

    private static byte[] time(Date date) {
      SimpleDateFormat format = new SimpleDateFormat("yyyyMMddHHmmss'Z'", Locale.ROOT);
      format.setTimeZone(TimeZone.getTimeZone("UTC"));
      // GeneralizedTime: valid for any year, where UTCTime stops at 2049.
      return tlv(0x18, format.format(date).getBytes(StandardCharsets.US_ASCII));
    }

    static byte[] oid(long... arcs) {
      ByteArrayOutputStream out = new ByteArrayOutputStream();
      out.write((int) (arcs[0] * 40 + arcs[1]));
      for (int i = 2; i < arcs.length; i++) {
        long arc = arcs[i];
        int shift = 0;
        while ((arc >> (shift + 7)) != 0) shift += 7;
        for (; shift > 0; shift -= 7) out.write((int) (0x80 | ((arc >> shift) & 0x7f)));
        out.write((int) (arc & 0x7f));
      }
      return tlv(0x06, out.toByteArray());
    }

    static byte[] seq(byte[] content) {
      return tlv(0x30, content);
    }

    static byte[] set(byte[] content) {
      return tlv(0x31, content);
    }

    static byte[] tlv(int tag, byte[] content) {
      ByteArrayOutputStream out = new ByteArrayOutputStream();
      out.write(tag);
      int length = content.length;
      if (length < 0x80) {
        out.write(length);
      } else {
        int bytes = 0;
        for (int l = length; l > 0; l >>= 8) bytes++;
        out.write(0x80 | bytes);
        for (int i = bytes - 1; i >= 0; i--) out.write((length >> (8 * i)) & 0xff);
      }
      out.write(content, 0, content.length);
      return out.toByteArray();
    }

    static byte[] cat(byte[]... parts) {
      ByteArrayOutputStream out = new ByteArrayOutputStream();
      for (byte[] part : parts) out.write(part, 0, part.length);
      return out.toByteArray();
    }

    private SelfSigned() {}
  }
}
