package ee.schimke.composeai.cli

import java.io.File
import java.security.MessageDigest
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.contentOrNull

/**
 * rules_compose_preview's Android aspect as the CLI installs it into a workspace that does not
 * fetch `@rules_compose_preview` (compose-ai-tools#5945): `android.bzl` with the `runtime.bzl`,
 * `java_info.bzl`, `android_providers.bzl` and `link.sh` it loads, copied byte for byte from one
 * rules release (`provenance.json`). Its own package keeps the JVM aspect's files untouched.
 */
internal const val DEFAULT_BAZEL_ANDROID_ASPECT =
  "//.compose-preview/bazel/android:android.bzl%compose_preview_android_aspect"

internal const val BAZEL_ANDROID_ASPECT_DIR = ".compose-preview/bazel/android"

private val ANDROID_ASPECT_FILES =
  listOf(
    "BUILD.bazel",
    "android.bzl",
    "android_providers.bzl",
    "java_info.bzl",
    "runtime.bzl",
    "link.sh",
  )

/** Marks a shim the CLI generated from `providers`; it is regenerated whenever they change. */
internal const val GENERATED_SHIM_HEADER =
  "# Generated by compose-preview from \"providers\" in .compose-preview/bazel.json; edit that.\n"

/** One symbol a shim exports: loaded from a `.bzl`, or a `Label` the rules use as-is. */
private data class ShimSymbol(val name: String, val default: String, val isLabel: Boolean)

/** The symbols each shim defines, with rules_compose_preview's own defaults. */
private val SHIMS: Map<String, List<ShimSymbol>> =
  mapOf(
    "java_info.bzl" to
      listOf(
        ShimSymbol("JavaInfo", "@rules_java//java/common:java_info.bzl", isLabel = false),
        ShimSymbol(
          "JavaRuntimeInfo",
          "@rules_java//java/common/rules:java_runtime.bzl",
          isLabel = false,
        ),
        ShimSymbol("JDK_RUNTIME", "@rules_java//toolchains:remotejdk_17", isLabel = true),
      ),
    "android_providers.bzl" to
      listOf(
        ShimSymbol("AndroidIdeInfo", "@rules_android//providers:providers.bzl", isLabel = false),
        ShimSymbol(
          "StarlarkAndroidResourcesInfo",
          "@rules_android//providers:providers.bzl",
          isLabel = false,
        ),
        ShimSymbol(
          "ANDROID_SDK_TOOLCHAIN_TYPE",
          "@rules_android//toolchains/android_sdk:toolchain_type",
          isLabel = true,
        ),
      ),
  )

/** Every symbol `providers` in bazel.json may set. */
internal val BAZEL_PROVIDER_SYMBOLS: Set<String> = SHIMS.values.flatten().map { it.name }.toSet()

private fun bundledAndroidAspectFile(name: String): String =
  requireNotNull(BazelCommand::class.java.getResourceAsStream("bazel/android/$name")) {
      "Missing bundled Android aspect file $name"
    }
    .bufferedReader()
    .use { it.readText() }

/**
 * A shim for [file] with [providers] applied: a provider symbol maps to the `.bzl` exporting it,
 * optionally `file.bzl%ExportedName` when its name there differs; a label symbol (`JDK_RUNTIME`,
 * `ANDROID_SDK_TOOLCHAIN_TYPE`) maps to the label. Unset symbols keep the rules' defaults.
 */
internal fun bazelProviderShim(file: String, providers: Map<String, String>): String {
  val symbols = requireNotNull(SHIMS[file]) { "No provider shim named $file" }
  val loads = linkedMapOf<String, MutableList<Pair<String, String>>>()
  val labels = mutableListOf<Pair<String, String>>()
  symbols.forEach { symbol ->
    val value = providers[symbol.name] ?: symbol.default
    if (symbol.isLabel) labels += symbol.name to value
    else {
      val bzl = value.substringBefore('%')
      val exported = value.substringAfter('%', symbol.name)
      require(bzl.endsWith(".bzl")) { "providers.${symbol.name} must name a .bzl file: $value" }
      loads.getOrPut(bzl) { mutableListOf() } += symbol.name to exported
    }
  }
  return buildString {
    append(GENERATED_SHIM_HEADER)
    loads.forEach { (bzl, names) ->
      append("load(${bazelJson.encodeToString(bzl)}")
      names.forEach { (local, exported) ->
        append(", _$local = ${bazelJson.encodeToString(exported)}")
      }
      append(")\n")
    }
    append("\n")
    loads.values.flatten().forEach { (local, _) -> append("$local = _$local\n") }
    labels.forEach { (name, label) ->
      append("$name = Label(${bazelJson.encodeToString(label)})\n")
    }
  }
}

/** What the Android aspect package should hold for [providers]: the shims generated only if set. */
internal fun bazelAndroidAspectContents(providers: Map<String, String>): Map<String, String> {
  val unknown = providers.keys - BAZEL_PROVIDER_SYMBOLS
  require(unknown.isEmpty()) {
    "Unknown providers ${unknown.joinToString()}; expected ${BAZEL_PROVIDER_SYMBOLS.joinToString()}"
  }
  return ANDROID_ASPECT_FILES.associateWith { name ->
    val shim = SHIMS[name]
    if (shim != null && shim.any { it.name in providers }) bazelProviderShim(name, providers)
    else bundledAndroidAspectFile(name)
  }
}

/** Records what the CLI wrote, so a later CLI can tell its own copies from a user's edits. */
private const val INSTALLED_RECORD = "installed.json"

private fun sha256(text: String): String =
  MessageDigest.getInstance("SHA-256").digest(text.toByteArray()).joinToString("") {
    "%02x".format(it)
  }

/**
 * Installs the Android aspect package under [root]. A file is written when it is missing, or when
 * it is still exactly what a CLI wrote there (`installed.json`, or a generated shim), so a newer
 * CLI upgrades its own copies; one edited by hand is kept. With [strict] (`bazel init`) a kept file
 * fails instead, so an explicit install never leaves a mixed package behind silently. Returns the
 * files it kept.
 */
internal fun installBazelAndroidAspect(
  root: File,
  providers: Map<String, String> = emptyMap(),
  strict: Boolean = false,
): List<File> {
  val directory = root.resolve(BAZEL_ANDROID_ASPECT_DIR)
  val contents = bazelAndroidAspectContents(providers)
  val record = directory.resolve(INSTALLED_RECORD)
  val installed = runCatching {
    bazelJson.parseToJsonElement(record.readText()) as JsonObject
  }
    .getOrNull()
    .orEmpty()
    .mapValues { (_, hash) -> (hash as? JsonPrimitive)?.contentOrNull }
  val kept = contents.mapNotNull { (name, text) ->
    val file = directory.resolve(name)
    val current = file.takeIf { it.isFile }?.readText()
    when {
      current == null || current == text -> null
      current.startsWith(GENERATED_SHIM_HEADER) -> null
      installed[name] == sha256(current) -> null
      else -> file
    }
  }
  require(!strict || kept.isEmpty()) {
    "Existing Android aspect files differ: ${kept.joinToString()}. Keep them and configure " +
      "aspect, or move them before reinitializing."
  }
  directory.mkdirs()
  contents.forEach { (name, text) ->
    val file = directory.resolve(name)
    if (file !in kept && (!file.isFile || file.readText() != text)) file.writeText(text)
  }
  val written =
    contents.filterKeys { name -> directory.resolve(name) !in kept }.mapValues { sha256(it.value) }
  record.writeText(
    bazelJson.encodeToString(
      JsonObject.serializer(),
      JsonObject(
        (installed.filterValues { it != null }.mapValues { JsonPrimitive(it.value) }) +
          written.mapValues { JsonPrimitive(it.value) }
      ),
    ) + "\n"
  )
  return kept
}
