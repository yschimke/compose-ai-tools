package ee.schimke.composeai.cli

import java.io.File
import javax.xml.parsers.DocumentBuilderFactory
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.contentOrNull

/**
 * The bundled BXL script's entry point, relative to the project root. Buck2 has no aspects; a BXL
 * script reads the same JVM and Android providers a build produced and prints the build-artifacts
 * documents the Bazel aspects write, so everything after collection is shared with the Bazel
 * driver.
 */
internal const val DEFAULT_BUCK_BXL = "//.compose-preview/buck/compose_preview.bxl:artifacts"

/**
 * Rules the BXL script reports, as a regex over rule names: JVM/Desktop libraries, and Android
 * libraries, whose resources it links into a standalone APK.
 */
internal const val DEFAULT_BUCK_TARGET_KINDS = "^(kotlin_library|java_library|android_library)$"

internal const val BUCK_BXL_DIR = ".compose-preview/buck"

/** Marks `link_sh.bxl`, generated from the bundled `link.sh`. */
internal const val LINK_SH_BXL_HEADER =
  "# Generated by compose-preview from rules_compose_preview's link.sh; do not edit.\n"

/**
 * `link_sh.bxl`: rules_compose_preview's `link.sh` (the copy bundled for the Android aspect) as a
 * string the BXL script writes out and runs. A source file outside any package cannot be an action
 * input, and `.compose-preview/buck` is no package.
 */
internal fun linkShBxl(linkSh: String): String {
  require("\"\"\"" !in linkSh && !linkSh.endsWith("\\")) { "link.sh cannot be a raw string" }
  return "${LINK_SH_BXL_HEADER}LINK_SH = r\"\"\"$linkSh\"\"\"\n"
}

private fun bundledText(resource: String): String =
  requireNotNull(BazelCommand::class.java.getResourceAsStream(resource)) {
      "Missing bundled $resource"
    }
    .bufferedReader()
    .use { it.readText() }

/**
 * SHA-256 of each file as an earlier release wrote it, before `installed.json` recorded them: the
 * JVM-only script 2.65.0 and 2.66.0 installed is the CLI's own and is upgraded, not kept.
 */
private val PREVIOUS_BUCK_BXL_FILES =
  mapOf(
    "compose_preview.bxl" to
      setOf("d0c77d4d7859528316a7631223ebb8d78088cd61b18e9313bd07fadbad35af82")
  )

/** Names Buck2 reads a package from by default (`[buildfile] name`). */
private val BUCK_PACKAGE_FILES = listOf("BUCK", "BUCK.v2", "TARGETS", "TARGETS.v2")

/**
 * The project root: the directory holding `.buckroot`, else the outermost `.buckconfig` below the
 * repository boundary. A cell inside the project (a vendored prelude, say) carries its own
 * `.buckconfig`, so the nearest one is not necessarily the root.
 */
internal fun detectBuckRoot(start: File): File? {
  var directory: File? = start.canonicalFile
  var outermost: File? = null
  while (directory != null) {
    val dir = directory
    if (dir.resolve(".buckroot").isFile) return dir
    if (dir.resolve(".buckconfig").isFile) outermost = dir
    if (dir.resolve(".git").exists() || dir.resolve(".hg").exists()) break
    directory = dir.parentFile
  }
  return outermost
}

internal fun isBuckProjectMarker(dir: File): Boolean =
  dir.resolve(".buckroot").isFile || dir.resolve(".buckconfig").isFile

/**
 * Installs the bundled BXL script and `link_sh.bxl` under [root]. A missing file, or one a CLI
 * wrote there, is (re)written, so a newer CLI upgrades its own copies; a locally adapted one is
 * kept, or with [strict] (`buck init`) fails. Returns the files it kept.
 */
internal fun installBuckBxl(root: File, strict: Boolean = false): List<File> =
  installCliOwnedFiles(
    root.resolve(BUCK_BXL_DIR),
    mapOf(
      "compose_preview.bxl" to bundledText("buck/compose_preview.bxl"),
      "link_sh.bxl" to linkShBxl(bundledText("bazel/android/link.sh")),
    ),
    strict,
    previous = PREVIOUS_BUCK_BXL_FILES,
    regenerable = { it.startsWith(LINK_SH_BXL_HEADER) },
  ) { kept ->
    "Existing BXL files differ: ${kept.joinToString()}. Keep them and configure bxl, or move " +
      "them before reinitializing."
  }

internal class BuckBuild(
  private val execute: (List<String>, File, Long) -> String = BazelProcess::run
) {
  /**
   * The nearest package at or above [directory], as `//pkg:`; outside any package, everything below
   * [directory] (`//dir/...`). A configured `target`, then `targets`, wins.
   */
  fun selectTargets(root: File, directory: File, config: BazelBuildConfig): BazelTargetSelection {
    config.target?.let {
      return BazelTargetSelection(it, listOf(it))
    }
    if (config.targets.isNotEmpty())
      return BazelTargetSelection(config.targets.joinToString(" "), config.targets)
    val canonicalRoot = root.canonicalFile
    var current: File? = directory.canonicalFile
    while (current != null && current.startsWith(canonicalRoot)) {
      val dir = current
      if (BUCK_PACKAGE_FILES.any { dir.resolve(it).isFile }) {
        val pattern = "//${dir.relativeTo(canonicalRoot).invariantSeparatorsPath}:"
        return BazelTargetSelection(pattern, listOf(pattern))
      }
      current = dir.parentFile
    }
    val relative =
      directory.canonicalFile
        .takeIf { it.startsWith(canonicalRoot) }
        ?.relativeTo(canonicalRoot)
        ?.invariantSeparatorsPath
        .orEmpty()
    val pattern = if (relative.isEmpty()) "//..." else "//$relative/..."
    return BazelTargetSelection(pattern, listOf(pattern))
  }

  /** `buck2 [startup] bxl [buildArgs] <bxl> -- --kinds <regex> --target <t>...` */
  fun argv(targets: List<String>, config: BazelBuildConfig): List<String> = buildList {
    addAll(config.buildCommand)
    addAll(config.startupArgs)
    add("bxl")
    addAll(config.buildArgs)
    add(config.bxl)
    add("--")
    add("--kinds")
    add(config.targetKinds ?: DEFAULT_BUCK_TARGET_KINDS)
    targets.forEach {
      add("--target")
      add(it)
    }
  }

  /**
   * Builds [targets] through the BXL script and resolves each library it reports against [root],
   * Buck2's execution root. With [skipWithoutMetadata] (a pattern's candidates) an empty result is
   * allowed; a target named explicitly must be a JVM or Android library.
   */
  fun collectAll(
    root: File,
    targets: List<String>,
    config: BazelBuildConfig,
    timeout: Long,
    skipWithoutMetadata: Boolean,
  ): List<ResolvedBazelArtifacts> {
    require(targets.none { it.startsWith("-") }) {
      "Buck2 target patterns cannot exclude (${targets.filter { it.startsWith("-") }.joinToString()}); " +
        "select the packages to include instead"
    }
    val documents = parseBuckArtifacts(execute(argv(targets, config), root, timeout))
    check(documents.isNotEmpty() || skipWithoutMetadata) {
      "No JVM or Android library among ${targets.joinToString(" ")}: the BXL script reads rules " +
        "matching ${config.targetKinds ?: DEFAULT_BUCK_TARGET_KINDS}; set targetKinds in " +
        ".compose-preview/buck.json for another rule"
    }
    return documents
      .map { withManifestPackage(it, root) }
      .map { text ->
        bazelJson
          .decodeFromString<BazelArtifacts>(text)
          .resolve(root, root, config.androidCompileSdk, bazelRuntimeJarOwners(text))
      }
  }
}

/** `//pkg:` (a package's targets) and `//dir/...`; a full label names one target. */
internal fun isBuckTargetPattern(target: String): Boolean =
  target.endsWith("...") || target.endsWith(":")

/**
 * [document] with an empty `android.packageName` filled from its manifest's `package`. The BXL
 * script takes the package from the library's `android_resource` deps; one without any leaves it to
 * the manifest, which BXL cannot read.
 */
internal fun withManifestPackage(document: String, root: File): String {
  val json = bazelJson.parseToJsonElement(document) as JsonObject
  val android = json["android"] as? JsonObject ?: return document
  if ((android["packageName"] as? JsonPrimitive)?.contentOrNull?.isNotBlank() == true) {
    return document
  }
  val path = (android["manifest"] as? JsonPrimitive)?.contentOrNull ?: return document
  val manifest = File(path).let { if (it.isAbsolute) it else root.resolve(path) }
  val pkg = runCatching {
    DocumentBuilderFactory.newInstance()
      .newDocumentBuilder()
      .parse(manifest)
      .documentElement
      .getAttribute("package")
  }
    .getOrNull()
    .orEmpty()
  require(pkg.isNotBlank()) {
    "${json["target"]}: no package name: give the library an android_resource with package, " +
      "or a manifest with one ($manifest)"
  }
  val filled = JsonObject(android + ("packageName" to JsonPrimitive(pkg)))
  return bazelJson.encodeToString(JsonObject.serializer(), JsonObject(json + ("android" to filled)))
}

/** Each document of the BXL script's `{"targets": [...]}`, re-encoded for the typed decode. */
internal fun parseBuckArtifacts(stdout: String): List<String> {
  // `print_json` writes one object; anything a wrapper prints before it is skipped.
  val start = stdout.indexOf('{')
  check(start >= 0) { "The BXL script printed no artifacts document" }
  val document = bazelJson.parseToJsonElement(stdout.substring(start)) as? JsonObject
  val targets = document?.get("targets") as? JsonArray ?: error("BXL output has no targets array")
  return targets.map { bazelJson.encodeToString(JsonObject.serializer(), it as JsonObject) }
}
