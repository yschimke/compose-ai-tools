#!/usr/bin/env node
/**
 * Regenerate the checked-in Google Fonts family list behind the `compose-preview serve` viewer's
 * `theme.font` autocomplete, so every fonts.google.com family is offered with no runtime API call.
 *
 *   node scripts/fonts/build-google-fonts-list.mjs           # fetch canonical source + rewrite
 *   node scripts/fonts/build-google-fonts-list.mjs --from x.csv   # build from a local CSV
 *   node scripts/fonts/build-google-fonts-list.mjs --check    # verify the checked-in file is current
 *
 * Source: `google/fonts`' `tags/all/families.csv`, whose first column is the display name as
 * `Font(GoogleFont("<name>"))` spells it (reachable without an API key, unlike
 * `fonts.google.com/metadata/fonts`). Output is newline-delimited, with `#` provenance lines.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { parseArgs } from "node:util";

// The list is a server resource, so `OUT` writes into a sibling compose-preview-server checkout
// (`COMPOSE_PREVIEW_SERVER_ROOT`, else `../compose-preview-server`); commit the change there. TODO:
// move this script to that repository.
const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const SERVER_ROOT =
  (process.env.COMPOSE_PREVIEW_SERVER_ROOT ?? "").trim() ||
  join(REPO_ROOT, "..", "compose-preview-server");
const OUT = join(
  SERVER_ROOT,
  "server/src/main/resources/ee/schimke/composeai/cli/serve/google-fonts.txt",
);
/** Pinned to `main` — the tag export tracks the live catalog; `--check` in CI flags drift. */
const SOURCE_URL =
  "https://raw.githubusercontent.com/google/fonts/main/tags/all/families.csv";

/**
 * The de-duplicated family names from a `families.csv` body (one row per tag), sorted
 * case-insensitively, then by raw value for stability.
 */
export function familiesFromCsv(csv) {
  const names = new Set();
  for (const line of csv.split(/\r?\n/)) {
    if (!line) continue;
    const name = line.slice(0, line.indexOf(",") === -1 ? line.length : line.indexOf(",")).trim();
    if (name) names.add(name);
  }
  return [...names].sort((a, b) => a.localeCompare(b, "en", { sensitivity: "base" }) || (a < b ? -1 : a > b ? 1 : 0));
}

/** Render the committed file body: a provenance header + one family per line. */
export function renderList(families) {
  return (
    [
      "# Google Fonts family names — autocomplete suggestions for the serve `theme.font` knob.",
      `# Generated by scripts/fonts/build-google-fonts-list.mjs from ${SOURCE_URL}`,
      "# Do not edit by hand; re-run the script to refresh. Lines starting with '#' are ignored.",
      `# families: ${families.length}`,
    ].join("\n") +
    "\n" +
    families.join("\n") +
    "\n"
  );
}

async function loadCsv(fromPath) {
  if (fromPath) return await readFile(fromPath, "utf8");
  const res = await fetch(SOURCE_URL);
  if (!res.ok) throw new Error(`fetch ${SOURCE_URL} failed: ${res.status} ${res.statusText}`);
  return await res.text();
}

async function main() {
  const { values } = parseArgs({
    options: { from: { type: "string" }, check: { type: "boolean" } },
  });
  const families = familiesFromCsv(await loadCsv(values.from));
  if (families.length < 1000) {
    throw new Error(`only ${families.length} families parsed — source looks wrong, refusing to write`);
  }
  const body = renderList(families);
  if (values.check) {
    const existing = await readFile(OUT, "utf8").catch(() => "");
    if (existing !== body) {
      console.error(`[google-fonts] ${OUT} is stale — run: node scripts/fonts/build-google-fonts-list.mjs`);
      process.exit(1);
    }
    console.log(`[google-fonts] up to date (${families.length} families)`);
    return;
  }
  await mkdir(dirname(OUT), { recursive: true });
  await writeFile(OUT, body);
  console.log(`[google-fonts] wrote ${families.length} families to ${OUT}`);
}

// Only run when invoked directly, so the pure helpers can be imported by the test.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
